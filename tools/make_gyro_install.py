"""Builds tools/install_gyro.luau: a Studio command-bar script that installs the GyroAim gyro fix in
a place this repo doesn't sync (the Zombies place), or in any place without Rojo.

Run: python tools/make_gyro_install.py   (from the repo root, after changing GyroAim.luau or the
gyro part of TouchControls).

The script it writes:
1. creates or updates ReplicatedStorage.Shared.GyroAim with src/campaign/.../GyroAim.luau;
2. patches StarterPlayerScripts.TouchControls from the 3 Nov gyro code (as of commit 186969b)
   to the new one, hunk by hunk, each hunk matched exactly once, after backing the script up to
   ServerStorage._Backups. If TouchControls already uses GyroAim it is left alone; if any hunk
   doesn't match, nothing in TouchControls is changed and the report says which hunk.
"""

from __future__ import annotations

import difflib
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
MODULE = ROOT / "src/campaign/ReplicatedStorage/Shared/GyroAim.luau"
TOUCH = "src/campaign/StarterPlayer/StarterPlayerScripts/TouchControls.client.luau"
OLD_REV = "186969b"  # a commit with the 3 Nov gyro code; the hunks are the gyro change only
CONTEXT = 2


def long_string(text: str) -> str:
    level = 1
    while "]" + "=" * level + "]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[\n{text}]{eq}]"


def hunks(old: str, new: str):
    a = old.splitlines(keepends=True)
    b = new.splitlines(keepends=True)
    out = []
    for group in difflib.SequenceMatcher(None, a, b, autojunk=False).get_grouped_opcodes(CONTEXT):
        i1, i2 = group[0][1], group[-1][2]
        j1, j2 = group[0][3], group[-1][4]
        out.append(("".join(a[i1:i2]), "".join(b[j1:j2])))
    return out


def main():
    # Studio keeps scripts with \n line ends; match that whatever the checkout uses.
    old = subprocess.run(["git", "show", f"{OLD_REV}:{TOUCH}"], cwd=ROOT, capture_output=True, text=True, check=True, encoding="utf-8").stdout.replace("\r\n", "\n")
    new = (ROOT / TOUCH).read_text(encoding="utf-8").replace("\r\n", "\n")
    module = MODULE.read_text(encoding="utf-8").replace("\r\n", "\n")
    parts = hunks(old, new)
    # Each hunk must be unique in the old text, or the installer could patch the wrong place.
    for i, (o, _) in enumerate(parts):
        assert old.count(o) == 1, f"hunk {i + 1} is not unique"
    check = old
    for o, n in parts:
        check = check.replace(o, n, 1)
    assert check == new, "hunks don't rebuild the new TouchControls"

    lines = [
        "-- Generated by tools/make_gyro_install.py. Do not edit; edit GyroAim.luau / TouchControls and regenerate.",
        "-- Gyro aim fix (docs/GYRO-AIM.md). Paste into Studio's command bar in Edit mode (not Play), press",
        "-- Enter, read the Output, then save/publish the place.",
        'local SES = game:GetService("ScriptEditorService")',
        'local ReplicatedStorage = game:GetService("ReplicatedStorage")',
        'local ServerStorage = game:GetService("ServerStorage")',
        'local StarterPlayer = game:GetService("StarterPlayer")',
        "local report = {}",
        "",
        "local function backup(script: LuaSourceContainer)",
        '\tlocal folder = ServerStorage:FindFirstChild("_Backups") or Instance.new("Folder")',
        '\tfolder.Name = "_Backups"',
        "\tfolder.Parent = ServerStorage",
        '\tlocal name = script.Name .. "_beforeGyroAim"',
        "\tif not folder:FindFirstChild(name) then",
        "\t\tlocal copy = script:Clone()",
        "\t\tcopy.Name = name",
        '\t\tif copy:IsA("BaseScript") then',
        "\t\t\tcopy.Enabled = false",
        "\t\tend",
        "\t\tcopy.Parent = folder",
        "\tend",
        "end",
        "",
        "local function write(script: LuaSourceContainer, source: string)",
        "\tlocal ok, err = loadstring(source)",
        '\tassert(ok, script.Name .. " does not compile: " .. tostring(err))',
        "\tSES:UpdateSourceAsync(script, function()",
        "\t\treturn source",
        "\tend)",
        "end",
        "",
        f"local MODULE = {long_string(module)}",
        "",
        "-- 1. The module.",
        'local shared = ReplicatedStorage:FindFirstChild("Shared")',
        'assert(shared, "ReplicatedStorage.Shared is missing")',
        'local module = shared:FindFirstChild("GyroAim")',
        "if not module then",
        '\tmodule = Instance.new("ModuleScript")',
        '\tmodule.Name = "GyroAim"',
        "\tmodule.Parent = shared",
        '\ttable.insert(report, "GyroAim: created")',
        "else",
        "\tbackup(module :: ModuleScript)",
        '\ttable.insert(report, "GyroAim: updated")',
        "end",
        "write(module :: ModuleScript, MODULE)",
        "",
        "-- 2. TouchControls, hunk by hunk.",
        "local HUNKS = {",
    ]
    for o, n in parts:
        lines.append(f"\t{{ old = {long_string(o)}, new = {long_string(n)} }},")
    lines += [
        "}",
        'local touch = StarterPlayer.StarterPlayerScripts:FindFirstChild("TouchControls")',
        "if not touch then",
        '\ttable.insert(report, "TouchControls: not in this place (nothing to patch)")',
        'elseif touch.Source:find("Shared\\"):WaitForChild(\\"GyroAim\\")", 1, true) then',
        '\ttable.insert(report, "TouchControls: already uses GyroAim")',
        "else",
        "\tlocal source = touch.Source",
        "\tlocal missing = nil",
        "\tfor i, hunk in HUNKS do",
        "\t\tlocal a, b = source:find(hunk.old, 1, true)",
        "\t\tif not a then",
        "\t\t\tmissing = i",
        "\t\t\tbreak",
        "\t\tend",
        "\t\tsource = source:sub(1, a - 1) .. hunk.new .. source:sub(b + 1)",
        "\tend",
        "\tif missing then",
        '\t\ttable.insert(report, `TouchControls: NOT patched, its gyro code differs from the 3 Nov version (hunk {missing} of {#HUNKS} not found). Nothing in it was changed.`)',
        "\telse",
        "\t\tbackup(touch)",
        "\t\twrite(touch, source)",
        '\t\ttable.insert(report, "TouchControls: patched to GyroAim")',
        "\tend",
        "end",
        "",
        'print("[install_gyro]\\n" .. table.concat(report, "\\n"))',
        "",
    ]
    out = ROOT / "tools/install_gyro.luau"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} with {len(parts)} TouchControls hunks")


if __name__ == "__main__":
    main()
